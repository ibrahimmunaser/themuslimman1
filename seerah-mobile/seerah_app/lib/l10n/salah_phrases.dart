/// Translates [text] if it is a known Salah-page phrase or a known dynamic
/// pattern; otherwise returns it unchanged.
/// Current app language, kept in sync by CourseLangNotifier. Used where no
/// BuildContext exists (e.g. scheduled notifications).
String salahLang = 'en';

String translateSalah(String lang, String text) {
  if (lang == 'en') return text;
  final i = _langs.indexOf(lang);
  if (i < 0) return text;
  final hit = _p[text] ?? morePhrases[text] ?? extraPhrases[text];
  if (hit != null) return _brandName(lang, hit[i]);
  if (RegExp(r'^(FAJR|DHUHR|ASR|MAGHRIB|ISHA)$').hasMatch(text)) {
    final t = text[0] + text.substring(1).toLowerCase();
    return translateSalah(lang, t).toUpperCase();
  }

  // "in 1h 14m" countdown.
  final cd = RegExp(r'^in (.+)$').firstMatch(text);
  if (cd != null && RegExp(r'^[\dhms ]+$').hasMatch(cd.group(1)!)) {
    final u = _units[lang] ?? const ['h', 'm', 's'];
    final t = cd.group(1)!.replaceAllMapped(RegExp(r'(\d+)([hms])'), (m) {
      final idx = 'hms'.indexOf(m.group(2)!);
      return '${m.group(1)}${u[idx]}';
    });
    return (_inTpl[lang] ?? 'in {t}').replaceAll('{t}', t);
  }

  // "Did you complete Maghrib?"
  final dc = RegExp(r'^Did you complete (\w+)\?$').firstMatch(text);
  if (dc != null) {
    final name = translateSalah(lang, dc.group(1)!);
    return (_didTpl[lang] ?? 'Did you complete {p}?').replaceAll('{p}', name);
  }

  // "Qibla is 56° NE of true North" / "1234 km to the Kaaba, Makkah".
  final km = RegExp(r'^(\d+) km to the Kaaba, Makkah$').firstMatch(text);
  if (km != null) {
    return (_kmTpl[lang] ?? '{n} km to the Kaaba, Makkah').replaceAll(
      '{n}',
      km.group(1)!,
    );
  }
  final bear = RegExp(
    r'^Qibla is (\d+)° (\w+) of true North$',
  ).firstMatch(text);
  if (bear != null) {
    return (_bearTpl[lang] ?? 'Qibla is {n}° {p} of true North')
        .replaceAll('{n}', bear.group(1)!)
        .replaceAll('{p}', compassWord(lang, bear.group(2)!));
  }
  // "6:33 PM" -> localized AM/PM marker.
  final tm = RegExp(r'^(\d{1,2}:\d{2}) (AM|PM)$').firstMatch(text);
  if (tm != null) {
    if (const ['fr', 'de', 'id', 'sw', 'ru', 'tr'].contains(lang)) {
      // 24-hour clock is the norm in these languages.
      final parts = tm.group(1)!.split(':');
      var h = int.parse(parts[0]) % 12;
      if (tm.group(2) == 'PM') h += 12;
      final hh = lang == 'fr' || lang == 'de' || lang == 'ru' || lang == 'tr'
          ? h.toString().padLeft(2, '0')
          : h.toString();
      return '$hh:${parts[1]}';
    }
    final m = _ampm[lang] ?? (lang == 'ms' ? const ['PG', 'PTG'] : null);
    if (m == null) return text;
    return '${tm.group(1)} ${tm.group(2) == 'AM' ? m[0] : m[1]}';
  }

  // Home date line: "3 Jumada Al-Thani 1448 AH  •  Fri, Nov 13".
  final dl = RegExp(
    r'^(\d+) (.+) (\d+) AH  •  (\w{3}), (\w{3}) (\d+)$',
  ).firstMatch(text);
  if (dl != null) {
    final month = _hijriMonth(lang, dl.group(2)!);
    final ah = _ah[lang] ?? 'AH';
    var greg = '${dl.group(4)}, ${dl.group(5)} ${dl.group(6)}';
    try {
      const mons = [
        'Jan',
        'Feb',
        'Mar',
        'Apr',
        'May',
        'Jun',
        'Jul',
        'Aug',
        'Sep',
        'Oct',
        'Nov',
        'Dec',
      ];
      final mi = mons.indexOf(dl.group(5)!) + 1;
      final now = DateTime.now();
      greg = DateFormat(
        'EEE, MMM d',
        lang,
      ).format(DateTime(now.year, mi, int.parse(dl.group(6)!)));
    } catch (_) {}
    return '${dl.group(1)} $month ${dl.group(3)} $ah  •  $greg';
  }
  return translateSalahDynamic(lang, text);
}

