  if (!s.contains('App Guard')) return s;
  switch (lang) {
    case 'ur':
      return s.replaceAll('App Guard', 'ایپ گارڈ');
    case 'hi':
      return s.replaceAll('App Guard', 'ऐप गार्ड');
