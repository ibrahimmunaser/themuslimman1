/// Looks up a Quran-page string; falls back to English.
String tq(String lang, String key, [Map<String, Object>? args]) {
  final i = _keys.indexOf(key);
  if (i < 0) return key;
  final list = _tr[lang] ?? _tr['en']!;
  var s = i < list.length ? list[i] : _tr['en']![i];
  if (args != null) {
    args.forEach((k, v) {
      s = s.replaceAll('{$k}', localizeNumerals(lang, '$v'));
    });
  }
  return s;
}
